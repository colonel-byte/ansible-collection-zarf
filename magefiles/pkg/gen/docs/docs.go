// Package docs runs every generator the book is built from: the Ansible collection reference
// (ansible.go and the three files it shares its rendering with), the Go package reference
// (golang.go), the two pages copied in from outside docs/ (book.go), and the table of contents
// that ties them together (summary.go).
//
// These generators came from colonel-byte/cargoship, where the proof this repository holds was
// first built. What was dropped on the way is everything that documented a CLI: the cobra command
// tree, the phase model, and the JSON schema pages. This repository ships no command of its own --
// its two binaries are Ansible module files, documented as modules rather than as commands.
package docs

import (
	"os"
)

// generatedBanner marks a page as generator output, so that an editor who opens one is told
// before they change it that their change will not survive the next commit. Shared by ansible.go,
// book.go and summary.go, the files that write generated pages.
const generatedBanner = "<!-- Page generated by colonel-byte/ansible-collection-zarf; DO NOT EDIT -->"

// golangDocsDir is where gomarkdoc writes one page per Go package, mirroring the package's own
// directory path under it (internal/zarfmod -> docs/golang/internal/zarfmod.md). Shared with
// golang.go, which renders into it.
const golangDocsDir = "docs/golang"

// GenerateDocument writes every generated page in the book.
//
// Only golangDocsDir is emptied first. docs/ansible holds hand-written overviews beside its
// generated pages, so ansible.go removes its own output by pattern instead; everywhere else under
// docs/ is hand-written.
func GenerateDocument() error {
	if err := os.RemoveAll(golangDocsDir); err != nil {
		return err
	}
	if err := os.MkdirAll(golangDocsDir, 0o775); err != nil {
		return err
	}

	if err := generateAnsibleDocs(); err != nil {
		return err
	}
	if err := generateBookPages(); err != nil {
		return err
	}

	return generateSummary()
}
