package pkgvendor

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// manifestImage matches an image reference in a vendored manifest. The indentation is not anchored
// and the leading `- ` of a list item is optional: an image appears at whatever depth its container
// sits at, and `- image:` is the spelling when the container's first key happens to be that one.
// Over-matching here is harmless -- a name with no repository, or one that already carries a
// registry, is skipped below.
//
// The horizontal whitespace is spelled out rather than written \s, which also matches a newline and
// would let the pattern start matching on the line before.
var manifestImage = regexp.MustCompile(`(?m)^[ \t]*(?:- )?image:[ \t]*(\S+)[ \t]*$`)

// rehomedImages returns the image names in one project's manifests that have no registry host, so
// that the generated kustomization can re-home them onto one.
//
// An image is judged to have no registry by the same rule the OCI tooling uses: the part before the
// first slash is a host only if it holds a dot or a colon. `fluxcd/source-controller` has neither,
// so it is a Docker Hub name; `ghcr.io/fluxcd/source-controller` has a dot and is left alone.
//
// The tag is deliberately dropped from the name. A kustomize image transform with a newName and no
// newTag keeps whatever tag the manifest carries, which is what makes this safe when the pin moves:
// the vendored manifest's tag is the upstream's, and nothing here gets a say in it.
func rehomedImages(directory string, project Project, registry string) ([]string, error) {
	if registry == "" {
		return nil, nil
	}

	names := map[string]bool{}
	for _, file := range project.Match {
		source, err := os.ReadFile(filepath.Join(directory, file)) //nolint:gosec // a file just written by Vendor
		if err != nil {
			return nil, err
		}
		for _, match := range manifestImage.FindAllSubmatch(source, -1) {
			reference := strings.Trim(string(match[1]), `"'`)
			name, _, _ := strings.Cut(reference, ":")
			host, _, found := strings.Cut(reference, "/")
			if !found || strings.ContainsAny(host, ".:") {
				continue
			}
			names[name] = true
		}
	}

	rehomed := make([]string, 0, len(names))
	for name := range names {
		rehomed = append(rehomed, name)
	}
	sort.Strings(rehomed)
	return rehomed, nil
}

// KustomizationFile is the generated file in each vendored project directory.
const KustomizationFile = "kustomization.yaml"

// generatedBanner marks the file as generator output, so that an editor who opens one is told
// before they change it that their change will not survive the next `examples:vendor`.
const generatedBanner = "# File generated by colonel-byte/ansible-collection-zarf; DO NOT EDIT"

// versionLabel is the label the generated kustomization stamps the pinned release onto every
// resource with, and it is the point of generating the file at all.
//
// Neither engine's upstream manifests carry it. Flux's carry `app.kubernetes.io/part-of: flux`
// and a per-controller `app.kubernetes.io/component`, and no version anywhere: the controllers'
// own versions (source-controller v1.9.5, helm-controller v1.6.4) are not the flux2 release.
// Argo CD's install.yaml carries no version label at all. `flux install` adds one from its own
// build; a package that vendors either upstream has to add it too, or the cluster cannot answer
// the question.
//
// That is not a tidiness argument. The version under `requires.fluxcd` or `requires.argocd` in a
// PackagePrerequisites document is
// checked by the prerequisites role reading this label off the engine's own workloads. Without it
// the constraint is reported as unchecked -- honestly, but uselessly.
const versionLabel = "app.kubernetes.io/version"

// partOfLabel is what upstream already sets, repeated here so that every resource in the project
// carries it, including the ones that do not today.
const partOfLabel = "app.kubernetes.io/part-of"

// writeKustomization writes one project's kustomization.yaml.
//
// `includeSelectors: false` is load-bearing. A label that reached the selectors would be added to
// each Deployment's `spec.selector.matchLabels`, which is immutable after creation, so the next
// pin bump would fail to upgrade an existing install rather than roll it -- and it would fail at
// deploy time on a cluster, which is the worst place to find out.
func writeKustomization(directory string, resources *Resources, project Project) error {
	var builder strings.Builder

	builder.WriteString("---\n")
	builder.WriteString(generatedBanner + "\n")
	builder.WriteString("#\n")
	fmt.Fprintf(&builder, "# %s %s, vendored from %s by `mage examples:vendor`.\n",
		project.Path, resources.Tag, resources.Repo)
	fmt.Fprintf(&builder, "# The resource list is the `match` of the %s project in ../../%s.\n",
		project.Path, ResourcesFile)
	builder.WriteString("apiVersion: kustomize.config.k8s.io/v1beta1\n")
	builder.WriteString("kind: Kustomization\n")
	fmt.Fprintf(&builder, "namespace: %s\n", resources.Namespace)
	builder.WriteString("labels:\n")
	builder.WriteString("  # includeSelectors stays false: a label added to a Deployment's\n")
	builder.WriteString("  # spec.selector.matchLabels cannot be changed afterwards, so stamping the\n")
	builder.WriteString("  # release into the selectors would make the next pin bump unupgradable.\n")
	builder.WriteString("  - includeSelectors: false\n")
	builder.WriteString("    pairs:\n")
	fmt.Fprintf(&builder, "      %s: %s\n", partOfLabel, resources.PartOf)
	fmt.Fprintf(&builder, "      %s: %s\n", versionLabel, resources.Tag)
	builder.WriteString("resources:\n")
	for _, name := range project.Match {
		// The basename, because that is the name the file was written under beside this
		// kustomization: a tree-sourced Match carries the directory it came from upstream, and
		// kustomize resolves a resource path relative to the kustomization rather than to a
		// source tree it knows nothing about.
		fmt.Fprintf(&builder, "  - %s\n", filepath.Base(name))
	}

	rehomed, err := rehomedImages(directory, project, resources.Registry)
	if err != nil {
		return err
	}
	if len(rehomed) > 0 {
		builder.WriteString("images:\n")
		builder.WriteString("  # Re-homed onto " + resources.Registry + ": upstream names these\n")
		builder.WriteString("  # without a registry, which resolves to a rate-limited Docker Hub.\n")
		builder.WriteString("  # The tag is left to the manifest, so a transform here cannot move it.\n")
		for _, name := range rehomed {
			fmt.Fprintf(&builder, "  - name: %s\n", name)
			fmt.Fprintf(&builder, "    newName: %s/%s\n", resources.Registry, name)
		}
	}

	path := filepath.Join(directory, KustomizationFile)
	fmt.Println(path)
	return os.WriteFile(path, []byte(builder.String()), 0o644) //nolint:gosec // generated manifests are world-readable
}
